"""Export a few test networks for the interactive page in docs/.

Writes docs/networks.js (the networks, with a position for each bank) and
docs/fixture.json (cascade sizes computed by the Python simulator, used by
tests/viewer.test.mjs to check that the page computes the same thing).
"""

import json

import networkx as nx
import numpy as np

from cascades.generate import N_CORE, make_network
from cascades.sim import all_cascades

LGD, TAU_CHECK = 0.6, [0.3, 0.5, 0.75]


def layout(net):
    n = net.n
    if net.family == "cp":
        pos = np.zeros((n, 2))
        core = np.arange(N_CORE)
        ang = 2 * np.pi * core / N_CORE
        pos[core] = 0.22 * np.column_stack([np.cos(ang), np.sin(ang)])
        A = (net.E + net.E.T) > 0
        # each periphery bank sits near the core bank it deals with most
        main = np.array([np.argmax((net.E + net.E.T)[i, :N_CORE]) if A[i, :N_CORE].any() else i % N_CORE
                         for i in range(N_CORE, n)])
        order = np.argsort(main, kind="stable")
        ang = 2 * np.pi * (np.arange(n - N_CORE) + 0.5) / (n - N_CORE) - np.pi / N_CORE
        pos[N_CORE + order] = 0.47 * np.column_stack([np.cos(ang), np.sin(ang)])
        return pos + 0.5
    G = nx.from_numpy_array((net.E + net.E.T) > 0)
    p = nx.spring_layout(G, seed=net.seed, k=1.6 / np.sqrt(n), iterations=300)
    pos = np.array([p[i] for i in range(n)])
    pos = (pos - pos.min(axis=0)) / (pos.max(axis=0) - pos.min(axis=0))
    return 0.04 + 0.92 * pos


networks, fixture = [], []
for family, label in (("cp", "Core-periphery"), ("er", "Random")):
    for k, seed in enumerate((4000, 4001, 4002)):
        net = make_network(family, seed, tau_mean=1.0)
        E = np.round(net.E, 4)
        strength = np.round(net.tau, 6)  # each bank's threshold when the mean threshold is 1
        pos = np.round(layout(net), 4)
        lenders, borrowers = np.nonzero(E)
        networks.append({
            "id": f"{family}-{seed}", "family": family, "label": f"{label} network {k + 1}",
            "n": net.n, "strength": strength.tolist(), "pos": pos.tolist(),
            "links": [[int(i), int(j), float(E[i, j])] for i, j in zip(lenders, borrowers)],
        })
        assets = E.sum(axis=1)
        for tau in TAU_CHECK:
            capital = np.where(assets > 0, tau * strength * LGD * assets, 1.0)
            F, R, _ = all_cascades(E, capital, LGD)
            fixture.append({"id": f"{family}-{seed}", "tau": tau,
                            "sizes": (F.sum(axis=1) - 1).tolist(), "rounds": R.max(axis=1).tolist()})

with open("docs/networks.js", "w") as f:
    f.write("// Generated by experiments/04_export_viewer.py. Do not edit.\n")
    f.write("const NETWORKS = " + json.dumps(networks, separators=(",", ":")) + ";\n")
    f.write("if (typeof module !== 'undefined') module.exports = { NETWORKS };\n")
json.dump(fixture, open("docs/fixture.json", "w"), separators=(",", ":"))
print(len(networks), "networks,", len(fixture), "fixture rows")
